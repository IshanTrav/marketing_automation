// Feeds the media_prompt produced by the prompt layer straight into Veo 3.1.
// This is the real end-to-end check: does our generated prompt actually make a
// usable vertical reel? Run: npm run test-veo-prompt

import "dotenv/config";
import fs from "node:fs";
import { GoogleGenAI } from "@google/genai";

const apiKey = process.env.GEMINI_API_KEY;
if (!apiKey) { console.error("Missing GEMINI_API_KEY in .env"); process.exit(1); }

const MODEL = "veo-3.1-fast-generate-preview";

// Everything the Gemini Developer API lets us pin down. Left implicit these default to
// values we did not choose - notably enhancePrompt, which lets Veo rewrite the prompt
// we engineered.
//
// Rejected by the Gemini Developer API, Vertex only (SDK throws before the request):
//   seed, generateAudio, fps, outputGcsUri, pubsubTopic, compressionQuality,
//   labels, mask, resizeMode
//
// Rejected by veo-3.1 itself (400 from the server, not the SDK):
//   enhancePrompt - so we cannot tell Veo to skip its own prompt rewriting here
//   personGeneration: "allow_adult" - rejected too; people are generated by default
const VEO_CONFIG = {
  aspectRatio: "9:16",
  resolution: process.env.VEO_RESOLUTION || "1080p",
  durationSeconds: 8,
  negativePrompt:
    "on-screen text, captions, subtitles, watermarks, logos, brand names, " +
    "user interface elements, price tags, readable signage",
};

if (process.env.VEO_SEED) VEO_CONFIG.seed = Number(process.env.VEO_SEED);  // Vertex only
const SRC = process.argv[2] || "prompts/_last-test-output.json";

if (!fs.existsSync(SRC)) { console.error(`No ${SRC} — run npm run test-prompt first`); process.exit(1); }
const { dials, output } = JSON.parse(fs.readFileSync(SRC, "utf8"));
const prompt = output.media_prompt;

console.log(`model: ${MODEL}`);
console.log(`dials: ${Object.entries(dials).map(([k, v]) => `${k}=${v}`).join(", ")}\n`);
console.log("config: " + JSON.stringify(VEO_CONFIG));
console.log("\nPROMPT SENT TO VEO:\n" + prompt + "\n");

const ai = new GoogleGenAI({ apiKey });
const t0 = process.hrtime.bigint();

let operation = await ai.models.generateVideos({
  model: MODEL,
  prompt,
  config: VEO_CONFIG,
});

console.log("submitted, polling...");
let polls = 0;
while (!operation.done) {
  await new Promise((r) => setTimeout(r, 10000));
  operation = await ai.operations.getVideosOperation({ operation });
  console.log(`  poll ${++polls}${operation.done ? " — done" : ""}`);
}

const elapsed = Number(process.hrtime.bigint() - t0) / 1e9;

if (!operation.response?.generatedVideos?.length) {
  console.error("No video returned:", JSON.stringify(operation, null, 2).slice(0, 2000));
  process.exit(1);
}

const outPath = process.argv[3] || process.env.VEO_OUT || "prompts/_veo-test-output.mp4";
await ai.files.download({
  file: operation.response.generatedVideos[0].video,
  downloadPath: outPath,
});

const bytes = fs.statSync(outPath).size;
console.log(`\ndone in ${elapsed.toFixed(0)}s → ${outPath} (${(bytes / 1e6).toFixed(2)} MB)`);
